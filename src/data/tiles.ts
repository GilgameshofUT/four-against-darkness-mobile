// rows: '#' = floor. conns: [x, y, side, door?]. Starting tiles have an 'X' (entrance) connector.
export type Side = 'N' | 'S' | 'E' | 'W';
export type ConnDef = [number, number, Side, boolean] | [number, number, Side, boolean, 'X'];

export interface ShapeDef {
  id: string;
  corridor: boolean;
  rows: string[];
  conns: ConnDef[];
}

const R = (id: string, rows: string[], conns: ConnDef[]): ShapeDef => ({ id, corridor: false, rows, conns });
const C = (id: string, rows: string[], conns: ConnDef[]): ShapeDef => ({ id, corridor: true, rows, conns });

